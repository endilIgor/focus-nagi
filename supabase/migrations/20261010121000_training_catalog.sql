-- name/sets/mode: omitted keeps them, null is invalid. notes: omitted keeps it, null or blank clears it.
-- Switching mode requires the new mode's target in the same patch and clears the other target; a
-- non-null target for the other mode is invalid.
create or replace function public.api_training_exercise_update(p_routine_id bigint, p_id bigint, p_patch jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_uid uuid := app_private.require_health_access();
    v_row public.training_exercise;
    v_name text;
    v_sets int;
    v_mode text;
    v_repetitions int;
    v_duration int;
    v_notes text;
    v_target text;
    v_other text;
begin
    perform app_private.training_check_patch(
        p_patch, array['name', 'sets', 'mode', 'repetitions', 'durationSeconds', 'notes']);
    v_row := app_private.lock_training_exercise(v_uid, p_routine_id, p_id);

    v_name := case when p_patch ? 'name'
        then app_private.training_name(app_private.training_patch_text(p_patch, 'name', false))
        else v_row.name end;
    v_sets := case when p_patch ? 'sets'
        then app_private.training_int(p_patch -> 'sets', 'sets', 1, 1000)
        else v_row.sets end;
    v_mode := case when p_patch ? 'mode'
        then app_private.training_patch_text(p_patch, 'mode', false)
        else v_row.mode end;
    v_notes := case when p_patch ? 'notes'
        then app_private.training_notes(app_private.training_patch_text(p_patch, 'notes', true))
        else v_row.notes end;

    if v_mode = 'REPETITIONS' then
        v_target := 'repetitions';
        v_other := 'durationSeconds';
    elsif v_mode = 'DURATION' then
        v_target := 'durationSeconds';
        v_other := 'repetitions';
    else
        perform app_private.fail('VALIDATION_ERROR', 'mode must be one of REPETITIONS, DURATION.');
    end if;

    if p_patch ? v_other and pg_catalog.jsonb_typeof(p_patch -> v_other) <> 'null' then
        perform app_private.fail('VALIDATION_ERROR', pg_catalog.format('%s must be null in %s mode.', v_other, v_mode));
    end if;

    if p_patch ? v_target then
        if v_mode = 'REPETITIONS' then
            v_repetitions := app_private.training_int(p_patch -> v_target, v_target, 1, 1000);
        else
            v_duration := app_private.training_int(p_patch -> v_target, v_target, 1, 86400);
        end if;
    elsif v_mode <> v_row.mode then
        perform app_private.fail('VALIDATION_ERROR', pg_catalog.format('%s is required when switching to %s mode.', v_target, v_mode));
    else
        v_repetitions := v_row.repetitions;
        v_duration := v_row.duration_seconds;
    end if;

    perform app_private.training_check_exercise(v_sets, v_mode, v_repetitions, v_duration);

    update public.training_exercise
    set name = v_name,
        sets = v_sets,
        mode = v_mode,
        repetitions = v_repetitions,
        duration_seconds = v_duration,
        notes = v_notes,
        updated_at = app_private.clock_now()
    where id = p_id and routine_id = p_routine_id and user_id = v_uid
    returning * into v_row;
    return app_private.training_exercise_json(v_row);
end
$$;

create or replace function public.api_training_exercise_delete(p_routine_id bigint, p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_uid uuid := app_private.require_health_access();
