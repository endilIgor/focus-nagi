-- Personal training catalog: routines and their exercises (registration only, no daily log).
--
-- Every public.api_training_* function first calls app_private.require_health_access(), so only
-- signed-in, health-enabled accounts reach the catalog, and every query/write is scoped by the
-- returned auth.uid(). Exercises reference routines through a composite (routine_id, user_id)
-- foreign key: an exercise can never point at another account's routine, and deleting a routine
-- removes its exercises in the same statement. Order is creation order (id ascending).
--
-- Validation limits (also enforced by CHECK constraints): name 150, notes 2000, sets and
-- repetitions 1..1000, duration 1..86400 seconds, weekdays unique ISO days 1 (Monday)..7 (Sunday).
-- Structure only: no account rows are inserted. Idempotent.

-- Sorted, unique ISO weekdays with no nulls; the empty array means "no days".
create or replace function app_private.training_weekdays_valid(p_days smallint[])
returns boolean
language sql
immutable
set search_path = ''
as $$
    select p_days is not null
       and coalesce(pg_catalog.array_ndims(p_days), 1) = 1
       and not exists (select 1 from pg_catalog.unnest(p_days) d where d is null or d < 1 or d > 7)
       and p_days = coalesce(
           (select pg_catalog.array_agg(distinct d order by d) from pg_catalog.unnest(p_days) d),
           '{}'::smallint[])
$$;

-- ---------------------------------------------------------------- tables

create table if not exists public.training_routine (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    name varchar(150) not null check (btrim(name) <> ''),
    weekdays smallint[] not null default '{}' check (app_private.training_weekdays_valid(weekdays)),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint training_routine_id_user_key unique (id, user_id)
);

create index if not exists idx_training_routine_user on public.training_routine (user_id, id);

create table if not exists public.training_exercise (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    routine_id bigint not null,
    name varchar(150) not null check (btrim(name) <> ''),
    sets int not null check (sets between 1 and 1000),
    mode varchar(20) not null check (mode in ('REPETITIONS', 'DURATION')),
    repetitions int check (repetitions is null or repetitions between 1 and 1000),
    duration_seconds int check (duration_seconds is null or duration_seconds between 1 and 86400),
    notes text check (notes is null or (char_length(notes) <= 2000 and btrim(notes) <> '')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint training_exercise_target_check check (
        (mode = 'REPETITIONS' and repetitions is not null and duration_seconds is null)
        or (mode = 'DURATION' and duration_seconds is not null and repetitions is null)),
    constraint training_exercise_routine_fk foreign key (routine_id, user_id)
        references public.training_routine (id, user_id) on delete cascade
);

create index if not exists idx_training_exercise_routine on public.training_exercise (routine_id, id);
create index if not exists idx_training_exercise_user on public.training_exercise (user_id);

do $$
declare
    t text;
begin
    foreach t in array array['training_routine', 'training_exercise']
    loop
        execute format('alter table public.%I enable row level security', t);
        execute format('revoke all on table public.%I from public, anon, authenticated', t);
        execute format('revoke all on sequence public.%I from public, anon, authenticated', t || '_id_seq');

        execute format('drop policy if exists %I on public.%I', t || '_owner_select', t);
        execute format('drop policy if exists %I on public.%I', t || '_owner_insert', t);
        execute format('drop policy if exists %I on public.%I', t || '_owner_update', t);
        execute format('drop policy if exists %I on public.%I', t || '_owner_delete', t);

        execute format(
            'create policy %I on public.%I for select to authenticated using (user_id = (select auth.uid()))',
            t || '_owner_select', t);
        execute format(
            'create policy %I on public.%I for insert to authenticated with check (user_id = (select auth.uid()))',
            t || '_owner_insert', t);
        execute format(
            'create policy %I on public.%I for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))',
            t || '_owner_update', t);
        execute format(
            'create policy %I on public.%I for delete to authenticated using (user_id = (select auth.uid()))',
            t || '_owner_delete', t);
    end loop;
end
$$;

-- ---------------------------------------------------------------- validation helpers

-- Required name: non-blank, at most 150 characters as received; stored trimmed.
create or replace function app_private.training_name(p_name text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
begin
    if p_name is null or pg_catalog.btrim(p_name) = '' or pg_catalog.char_length(p_name) > 150 then
        perform app_private.fail('VALIDATION_ERROR', 'name must be 1-150 characters.');
    end if;
    return pg_catalog.btrim(p_name);
end
$$;

-- Optional notes: at most 2000 characters as received; blank becomes null.
create or replace function app_private.training_notes(p_notes text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
begin
    if p_notes is not null and pg_catalog.char_length(p_notes) > 2000 then
        perform app_private.fail('VALIDATION_ERROR', 'notes must be at most 2000 characters.');
    end if;
    return nullif(pg_catalog.btrim(p_notes), '');
end
$$;

create or replace function app_private.training_range(p_value int, p_field text, p_min int, p_max int)
returns int
language plpgsql
immutable
set search_path = ''
as $$
begin
    if p_value is null or p_value < p_min or p_value > p_max then
        perform app_private.fail('VALIDATION_ERROR', pg_catalog.format('%s must be between %s and %s.', p_field, p_min, p_max));
    end if;
    return p_value;
end
$$;

-- Integral JSON number within [p_min, p_max]; any other JSON type (including null) is rejected.
create or replace function app_private.training_int(p_value jsonb, p_field text, p_min int, p_max int)
returns int
language plpgsql
immutable
set search_path = ''
as $$
declare
    v numeric;
begin
    if p_value is null or pg_catalog.jsonb_typeof(p_value) <> 'number' then
        perform app_private.fail('VALIDATION_ERROR', pg_catalog.format('%s must be an integer.', p_field));
    end if;
    v := p_value::numeric;
    if v <> pg_catalog.trunc(v) or v < p_min or v > p_max then
        perform app_private.fail('VALIDATION_ERROR', pg_catalog.format('%s must be between %s and %s.', p_field, p_min, p_max));
    end if;
    return v::int;
end
$$;

-- Weekdays from an SQL array: null means none; values must be unique ISO days 1..7. Returns sorted.
create or replace function app_private.training_weekdays(p_days int[])
returns smallint[]
language plpgsql
immutable
set search_path = ''
as $$
declare
    v_days smallint[];
begin
    if p_days is null then
        return '{}'::smallint[];
    end if;
    if coalesce(pg_catalog.array_ndims(p_days), 1) <> 1
       or exists (select 1 from pg_catalog.unnest(p_days) d where d is null or d < 1 or d > 7) then
        perform app_private.fail('VALIDATION_ERROR', 'weekdays must be days 1-7.');
    end if;
    select coalesce(pg_catalog.array_agg(distinct d::smallint order by d::smallint), '{}'::smallint[])
    into v_days from pg_catalog.unnest(p_days) d;
    if pg_catalog.cardinality(v_days) <> pg_catalog.cardinality(p_days) then
        perform app_private.fail('VALIDATION_ERROR', 'weekdays must be unique.');
    end if;
    return v_days;
end
$$;

-- Weekdays from a JSON patch value: null clears them; otherwise an array of integers 1..7.
create or replace function app_private.training_weekdays(p_days jsonb)
returns smallint[]
language plpgsql
immutable
set search_path = ''
as $$
declare
    v_days int[] := '{}';
    v_item jsonb;
begin
    if p_days is null or pg_catalog.jsonb_typeof(p_days) = 'null' then
        return '{}'::smallint[];
    end if;
    if pg_catalog.jsonb_typeof(p_days) <> 'array' then
        perform app_private.fail('VALIDATION_ERROR', 'weekdays must be an array.');
    end if;
    for v_item in select e from pg_catalog.jsonb_array_elements(p_days) e
    loop
        v_days := v_days || app_private.training_int(v_item, 'weekdays', 1, 7);
    end loop;
    return app_private.training_weekdays(v_days);
end
$$;

-- Validates a complete exercise (mode and a single coherent target) and raises VALIDATION_ERROR.
create or replace function app_private.training_check_exercise(
    p_sets int, p_mode text, p_repetitions int, p_duration_seconds int)
returns void
language plpgsql
immutable
set search_path = ''
as $$
begin
    perform app_private.training_range(p_sets, 'sets', 1, 1000);
    if p_mode = 'REPETITIONS' then
        perform app_private.training_range(p_repetitions, 'repetitions', 1, 1000);
        if p_duration_seconds is not null then
            perform app_private.fail('VALIDATION_ERROR', 'durationSeconds must be null in REPETITIONS mode.');
        end if;
    elsif p_mode = 'DURATION' then
        perform app_private.training_range(p_duration_seconds, 'durationSeconds', 1, 86400);
        if p_repetitions is not null then
            perform app_private.fail('VALIDATION_ERROR', 'repetitions must be null in DURATION mode.');
        end if;
    else
        perform app_private.fail('VALIDATION_ERROR', 'mode must be one of REPETITIONS, DURATION.');
    end if;
end
$$;

-- p_patch must be a JSON object whose keys are all in p_allowed.
create or replace function app_private.training_check_patch(p_patch jsonb, p_allowed text[])
returns void
language plpgsql
immutable
set search_path = ''
as $$
begin
    if p_patch is null or pg_catalog.jsonb_typeof(p_patch) <> 'object' then
        perform app_private.fail('VALIDATION_ERROR', 'patch must be a JSON object.');
    end if;
    if exists (select 1 from pg_catalog.jsonb_object_keys(p_patch) k where k <> all (p_allowed)) then
        perform app_private.fail('VALIDATION_ERROR', 'patch contains unsupported fields.');
    end if;
end
$$;

-- Patch text value: must be a JSON string (or JSON null when p_nullable).
create or replace function app_private.training_patch_text(p_patch jsonb, p_key text, p_nullable boolean)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
    v_type text := pg_catalog.jsonb_typeof(p_patch -> p_key);
begin
    if v_type = 'string' or (p_nullable and v_type = 'null') then
        return p_patch ->> p_key;
    end if;
    perform app_private.fail('VALIDATION_ERROR', pg_catalog.format('%s must be a string.', p_key));
end
$$;

