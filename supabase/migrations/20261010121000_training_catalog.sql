-- name: omitted keeps it, null is invalid. weekdays: omitted keeps them, null clears them.
create or replace function public.api_training_routine_update(p_id bigint, p_patch jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_uid uuid := app_private.require_health_access();
    v_row public.training_routine;
    v_name text;
    v_days smallint[];
begin
    perform app_private.training_check_patch(p_patch, array['name', 'weekdays']);
    v_row := app_private.lock_training_routine(v_uid, p_id);
    v_name := case when p_patch ? 'name'
        then app_private.training_name(app_private.training_patch_text(p_patch, 'name', false))
        else v_row.name end;
    v_days := case when p_patch ? 'weekdays'
        then app_private.training_weekdays(p_patch -> 'weekdays')
        else v_row.weekdays end;
    update public.training_routine
    set name = v_name, weekdays = v_days, updated_at = app_private.clock_now()
    where id = p_id and user_id = v_uid
    returning * into v_row;
    return app_private.training_routine_json(v_row);
end
$$;

