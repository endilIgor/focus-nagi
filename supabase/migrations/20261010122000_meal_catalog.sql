-- Personal meal plan catalog: foods registered in four fixed meals (registration only, no daily
-- log, completion flag or nutrition data).
--
-- Every public.api_nutrition_food_* function first calls app_private.require_health_access(), so
-- only signed-in, health-enabled accounts reach the catalog, and every query/write is scoped by the
-- returned auth.uid(). Order is creation order (id ascending); moving a food to another meal keeps
-- its id and therefore its creation position.
--
-- Validation limits (also enforced by CHECK constraints): name 1..150 characters, optional free-text
-- quantity up to 150 characters; both trimmed, a blank quantity is stored as null.
-- Structure only: no account rows are inserted. Idempotent.

-- ---------------------------------------------------------------- table

create table if not exists public.nutrition_food (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    meal varchar(20) not null check (meal in ('BREAKFAST', 'LUNCH', 'AFTERNOON_SNACK', 'DINNER')),
    name varchar(150) not null check (btrim(name) <> ''),
    quantity varchar(150) check (quantity is null or btrim(quantity) <> ''),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_nutrition_food_user on public.nutrition_food (user_id, id);

alter table public.nutrition_food enable row level security;
revoke all on table public.nutrition_food from public, anon, authenticated;
revoke all on sequence public.nutrition_food_id_seq from public, anon, authenticated;

drop policy if exists nutrition_food_owner_select on public.nutrition_food;
drop policy if exists nutrition_food_owner_insert on public.nutrition_food;
drop policy if exists nutrition_food_owner_update on public.nutrition_food;
drop policy if exists nutrition_food_owner_delete on public.nutrition_food;

create policy nutrition_food_owner_select on public.nutrition_food
    for select to authenticated using (user_id = (select auth.uid()));
create policy nutrition_food_owner_insert on public.nutrition_food
    for insert to authenticated with check (user_id = (select auth.uid()));
create policy nutrition_food_owner_update on public.nutrition_food
    for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy nutrition_food_owner_delete on public.nutrition_food
    for delete to authenticated using (user_id = (select auth.uid()));

-- ---------------------------------------------------------------- validation helpers

-- One of the four fixed meals, exact (case-sensitive, untrimmed).
create or replace function app_private.nutrition_meal(p_meal text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
begin
    if p_meal is null or p_meal not in ('BREAKFAST', 'LUNCH', 'AFTERNOON_SNACK', 'DINNER') then
        perform app_private.fail('VALIDATION_ERROR', 'meal must be one of BREAKFAST, LUNCH, AFTERNOON_SNACK, DINNER.');
    end if;
    return p_meal;
end
$$;

-- Required name: non-blank, at most 150 characters as received; stored trimmed.
create or replace function app_private.nutrition_name(p_name text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
begin
    if p_name is null or pg_catalog.btrim(p_name) = '' or pg_catalog.char_length(p_name) > 150 then
        perform app_private.fail('VALIDATION_ERROR', 'name must be 1-150 characters.');
    end if;
    return pg_catalog.btrim(p_name);
end
$$;

-- Optional free-text quantity: at most 150 characters as received; blank becomes null.
create or replace function app_private.nutrition_quantity(p_quantity text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
begin
    if p_quantity is not null and pg_catalog.char_length(p_quantity) > 150 then
        perform app_private.fail('VALIDATION_ERROR', 'quantity must be at most 150 characters.');
    end if;
    return nullif(pg_catalog.btrim(p_quantity), '');
end
$$;

-- p_patch must be a JSON object whose keys are all meal, name or quantity.
create or replace function app_private.nutrition_check_patch(p_patch jsonb)
returns void
language plpgsql
immutable
set search_path = ''
as $$
begin
    if p_patch is null or pg_catalog.jsonb_typeof(p_patch) <> 'object' then
        perform app_private.fail('VALIDATION_ERROR', 'patch must be a JSON object.');
    end if;
    if exists (select 1 from pg_catalog.jsonb_object_keys(p_patch) k where k not in ('meal', 'name', 'quantity')) then
        perform app_private.fail('VALIDATION_ERROR', 'patch contains unsupported fields.');
    end if;
end
$$;

-- Patch text value: must be a JSON string (or JSON null when p_nullable).
create or replace function app_private.nutrition_patch_text(p_patch jsonb, p_key text, p_nullable boolean)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
    v_type text := pg_catalog.jsonb_typeof(p_patch -> p_key);
begin
    if v_type = 'string' or (p_nullable and v_type = 'null') then
        return p_patch ->> p_key;
    end if;
    perform app_private.fail('VALIDATION_ERROR', pg_catalog.format('%s must be a string.', p_key));
end
$$;

-- ---------------------------------------------------------------- lookup and JSON

create or replace function app_private.nutrition_food_json(f public.nutrition_food)
returns jsonb
language sql
stable
set search_path = ''
as $$
    select pg_catalog.jsonb_build_object(
        'id', f.id,
        'meal', f.meal,
        'name', f.name,
        'quantity', f.quantity,
        'createdAt', app_private.iso(f.created_at),
        'updatedAt', app_private.iso(f.updated_at)
    )
$$;

-- Read-only lookup (usable from STABLE functions); another account's id is reported as not found.
create or replace function app_private.find_nutrition_food(p_uid uuid, p_id bigint)
returns public.nutrition_food
language plpgsql
stable
set search_path = ''
as $$
declare
    v_row public.nutrition_food;
begin
    select * into v_row from public.nutrition_food where id = p_id and user_id = p_uid;
    if not found then
        perform app_private.fail('NUTRITION_FOOD_NOT_FOUND');
    end if;
    return v_row;
end
$$;

-- Locking lookup for writes.
create or replace function app_private.lock_nutrition_food(p_uid uuid, p_id bigint)
returns public.nutrition_food
language plpgsql
set search_path = ''
as $$
declare
    v_row public.nutrition_food;
begin
    select * into v_row from public.nutrition_food where id = p_id and user_id = p_uid for update;
    if not found then
        perform app_private.fail('NUTRITION_FOOD_NOT_FOUND');
    end if;
    return v_row;
end
$$;

-- ---------------------------------------------------------------- foods

create or replace function public.api_nutrition_food_create(p_meal text, p_name text, p_quantity text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_uid uuid := app_private.require_health_access();
    v_meal text := app_private.nutrition_meal(p_meal);
    v_name text := app_private.nutrition_name(p_name);
    v_quantity text := app_private.nutrition_quantity(p_quantity);
    v_now timestamptz := app_private.clock_now();
    v_row public.nutrition_food;
begin
    insert into public.nutrition_food (user_id, meal, name, quantity, created_at, updated_at)
    values (v_uid, v_meal, v_name, v_quantity, v_now, v_now)
    returning * into v_row;
    return app_private.nutrition_food_json(v_row);
end
$$;

create or replace function public.api_nutrition_food_get(p_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_uid uuid := app_private.require_health_access();
begin
    return app_private.nutrition_food_json(app_private.find_nutrition_food(v_uid, p_id));
end
$$;

-- Every meal's foods of the caller, in creation order; clients group them by meal.
create or replace function public.api_nutrition_food_list(p_page int, p_size int)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_uid uuid := app_private.require_health_access();
    v_page int := app_private.clamp_page(p_page);
    v_size int := app_private.clamp_size(p_size, 20);
    v_total bigint;
    v_content jsonb;
begin
    select pg_catalog.count(*) into v_total from public.nutrition_food f where f.user_id = v_uid;

    select coalesce(pg_catalog.jsonb_agg(app_private.nutrition_food_json(s.f) order by (s.f).id), '[]'::jsonb)
    into v_content
    from (
        select f from public.nutrition_food f
        where f.user_id = v_uid
        order by f.id
        limit v_size offset v_page::bigint * v_size
    ) s;

    return app_private.page_json(v_content, v_total, v_page, v_size);
end
$$;

-- meal/name: omitted keeps them, null is invalid; a new meal moves the food (same id, same position).
-- quantity: omitted keeps it, null or blank clears it. Everything is validated before the write.
create or replace function public.api_nutrition_food_update(p_id bigint, p_patch jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_uid uuid := app_private.require_health_access();
    v_row public.nutrition_food;
    v_meal text;
    v_name text;
    v_quantity text;
begin
    perform app_private.nutrition_check_patch(p_patch);
    v_row := app_private.lock_nutrition_food(v_uid, p_id);
    v_meal := case when p_patch ? 'meal'
        then app_private.nutrition_meal(app_private.nutrition_patch_text(p_patch, 'meal', false))
        else v_row.meal end;
    v_name := case when p_patch ? 'name'
        then app_private.nutrition_name(app_private.nutrition_patch_text(p_patch, 'name', false))
        else v_row.name end;
    v_quantity := case when p_patch ? 'quantity'
        then app_private.nutrition_quantity(app_private.nutrition_patch_text(p_patch, 'quantity', true))
        else v_row.quantity end;
    update public.nutrition_food
    set meal = v_meal, name = v_name, quantity = v_quantity, updated_at = app_private.clock_now()
    where id = p_id and user_id = v_uid
    returning * into v_row;
    return app_private.nutrition_food_json(v_row);
end
$$;

-- Returns JSON null (no payload), like the training deletions, so direct SQL callers and PostgREST
-- both observe null.
create or replace function public.api_nutrition_food_delete(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_uid uuid := app_private.require_health_access();
begin
    perform app_private.lock_nutrition_food(v_uid, p_id);
    delete from public.nutrition_food where id = p_id and user_id = v_uid;
    return null;
end
$$;

